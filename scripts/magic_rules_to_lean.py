#!/usr/bin/env python3
"""Instantiate the magic-constant division rules of generic.rules on concrete divisors.

For a concrete divisor c, `umagicN(c)` / `smagicN(c)` (magic.go) are computed here (Python
port, checked against Go by go/tests/magic_port_test.go), the rule's condition is evaluated
(`config.*` and `x.Op` conjuncts dropped: every variant is checked), and the instantiated
rule is translated by scripts/generic_rules_to_lean.py into a theorem over a symbolic
dividend x. Divisors: all 8-bit values, and fixed samples for 16/32/64 bits.
Modes and triage file work as in generic_rules_to_lean.py.
"""
import hashlib, json, os, re, subprocess, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import generic_rules_to_lean as g

ROOT = g.ROOT
OUT = os.path.join(ROOT, "GoInLean", "Compiler", "MagicDiv.lean")
TRIAGE = os.path.join(ROOT, "targets", "magic_rules_triage.json")

def umagic(n, c):
    d = c % (1 << n)
    s = d.bit_length()
    M = ((1 << (n + s)) + d - 1) // d
    assert (M >> n) & 1 == 1
    return (s, M & ~(1 << n))
def smagic(n, c):
    s = c.bit_length() - 1
    M = ((1 << (n + s)) + c - 1) // c
    assert (M >> n) & 1 == 0 and (M >> (n - 1)) & 1 == 1
    return (s, M)
def signed_of(n, v):
    v %= 1 << n
    return v - (1 << n) if v >= 1 << (n - 1) else v
def umagicOK(n, c): d = c % (1 << n); return d & (d - 1) != 0
def smagicOK(n, c): return c >= 0 and c & (c - 1) != 0

def samples(n):
    if n == 8:
        return list(range(-128, 128))
    base = [3, 5, 6, 7, 9, 10, 11, 12, 13, 25, 100, 641, 1000, 6700417 % (1 << (n - 1)),
            (1 << (n - 1)) - 1, (1 << (n - 2)) + 1, (1 << (n - 2)) - 1, (1 << (n - 1)) // 3, 7 << (n - 8),
            -1, -3, -7, -(1 << (n - 2)) - 1]
    if n >= 32: base += [1000003, 2147483647 % (1 << (n - 1)), 4294967291 % (1 << (n - 1))]
    if n == 64: base += [10**18 + 9, 3 << 60, 0x5555555555555555, -10**18 - 3]
    out = []
    for c in base:
        c = signed_of(n, c)
        if c not in out: out.append(c)
    return out

def eval_cond(cond, n, c):
    """True/False for the instantiated condition; config/Op conjuncts are dropped."""
    ok = True
    for part in g.split_conj(cond):
        p = part.replace(" ", "")
        if "config." in p or ".Op" in p: continue
        p = re.sub(r"umagicOK(8|16|32|64)\(int32\(c\)\)", lambda m: str(umagicOK(32, signed_of(32, c))), p)
        p = re.sub(r"umagicOK(8|16|32|64)\(c\)", lambda m: str(umagicOK(int(m.group(1)), c)), p)
        p = re.sub(r"smagicOK(8|16|32|64)\(c\)", lambda m: str(smagicOK(int(m.group(1)), c)), p)
        p = re.sub(r"umagic(8|16|32|64)\(c\)\.m", lambda m: str(umagic(int(m.group(1)), c)[1]), p)
        p = re.sub(r"smagic(8|16|32|64)\(c\)\.m", lambda m: str(smagic(int(m.group(1)), c)[1]), p)
        p = re.sub(r"\bc\b", f"({c})", p)
        p = p.replace("&&", " and ").replace("||", " or ").replace("!=", " != ")
        if re.search(r"[A-Za-z_]", p.replace("True", "").replace("False", "").replace("and", "").replace("or", "")):
            raise g.Skip("cond " + part)
        if not eval(p, {"__builtins__": {}}): ok = False
    return ok

def instantiate(rule, n, c):
    lhs, rhs = rule.split("=>", 1)
    m = re.match(r"(\(.*?\(Const\d+\s+\[c\]\)\))\s*&&\s*(.*)$", lhs.strip())
    if not m: raise g.Skip("shape")
    pat, cond = m.group(1), m.group(2)
    if not eval_cond(cond, n, c): return None
    def sub(text):
        text = re.sub(r"umagic(8|16|32|64)\(c\)\.m", lambda mm: str(umagic(int(mm.group(1)), c)[1]), text)
        text = re.sub(r"umagic(8|16|32|64)\(c\)\.s", lambda mm: str(umagic(int(mm.group(1)), c)[0]), text)
        text = re.sub(r"smagic(8|16|32|64)\(c\)\.m", lambda mm: str(smagic(int(mm.group(1)), c)[1]), text)
        text = re.sub(r"smagic(8|16|32|64)\(c\)\.s", lambda mm: str(smagic(int(mm.group(1)), c)[0]), text)
        return re.sub(r"\bc\b", f"({c})" if c < 0 else str(c), text)
    return sub(pat) + " => " + sub(rhs)

def collect():
    src = open(g.RULES).read()
    sha = hashlib.sha256(src.encode()).hexdigest()
    items, skipped = [], {}
    for lineno, rule in g.read_rules(src):
        if not re.search(r"[us]magic", rule): continue
        m = re.match(r"\((Div|Mod)(8|16|32|64)u?\s", rule)
        if not m: continue
        n = int(m.group(2))
        for c in samples(n):
            try:
                inst = instantiate(rule, n, c)
                if inst is None: continue
                tid = f"m{lineno}_{'n' if c < 0 else ''}{abs(c)}"
                items.append((tid, lineno, inst, g.translate(inst)))
            except (g.Skip, AssertionError) as e:
                skipped[str(e).split(" ")[0]] = skipped.get(str(e).split(" ")[0], 0) + 1
    return sha, items, skipped

def render(sha, items, excluded):
    keep = [it for it in items if it[0] not in excluded]
    text = (f"-- Code generated by scripts/magic_rules_to_lean.py from generic.rules. DO NOT EDIT.\n"
            f"-- Source sha256 {sha}; {len(keep)} instances proved, {len(excluded)} excluded after triage.\n"
            "import Std.Tactic.BVDecide\nimport GoInLean.Compiler.GenericSem\n\nset_option maxRecDepth 8192\n"
            "namespace Go.Compiler.MagicDiv\nopen Go.Compiler Go\n\n")
    text += "\n".join(g.theorem(*it) for it in keep) + "\nend Go.Compiler.MagicDiv\n"
    return text

def main():
    sha, items, skipped = collect()
    print(f"{len(items)} instances; skipped {skipped}")
    if "--triage" in sys.argv:
        text = render(sha, items, set())
        tmp = os.path.join(ROOT, "build", "MagicTriage.lean"); open(tmp, "w").write(text)
        r = subprocess.run(["lake", "env", "lean", tmp], cwd=ROOT, text=True, capture_output=True, timeout=14400)
        out = r.stdout + r.stderr
        if (r.returncode != 0 and ": error" not in out) or "PANIC" in out:
            raise SystemExit("lean crashed during triage:\n" + out[-2000:])
        starts = [(text.count("\n", 0, mm.start()) + 1, mm.group(1)) for mm in re.finditer(r"^theorem (\w+)", text, re.M)]
        res = {}
        for mm in re.finditer(r"MagicTriage\.lean:(\d+):\d+: error: (.*)", out):
            ln = int(mm.group(1)); tid = None
            for l, t in starts:
                if l <= ln: tid = t
            seg = out[mm.start(): mm.start() + 600]
            seg = re.split(r"\n[^\n]*\.lean:\d+:\d+: error", seg, maxsplit=1)[0]
            cat = ("counterexample" if "found a counterexample" in seg and "potentially spurious" not in seg
                   else "spurious" if "potentially spurious" in seg else "timeout" if "time" in seg else "elab_error")
            res.setdefault(tid, {"category": cat, "detail": seg})
        for tid, lineno, r_, _ in items:
            if tid in res: res[tid]["rule"] = r_; res[tid]["line"] = lineno
        json.dump(res, open(TRIAGE, "w"), indent=1, sort_keys=True)
        from collections import Counter
        print("triage:", Counter(v["category"] for v in res.values()))
    excluded = set(json.load(open(TRIAGE))) if os.path.exists(TRIAGE) else set()
    text = render(sha, items, excluded)
    if "--check" in sys.argv:
        if open(OUT).read() != text: raise SystemExit("MagicDiv.lean is out of date")
        print("MagicDiv.lean up to date"); return
    open(OUT, "w").write(text)
    print(f"wrote {os.path.relpath(OUT, ROOT)}: {len(items) - len(excluded)} theorems")

if __name__ == "__main__":
    main()
