#!/usr/bin/env python3
"""Generate GoInLean/Stdlib/BitsTables.lean from Go's src/math/bits/bits_tables.go.

The Go file is treated as untrusted *data*: we only parse Go string literals
made of \\xNN escapes. The output is a Lean file defining the four lookup
tables as explicit `Array (BitVec 8)` literals so that the Lean kernel can
evaluate them by `decide` and the correspondence to Go is byte-for-byte
auditable (run with --check to verify the committed file is up to date).
"""
import hashlib, os, re, subprocess, sys

def goroot():
    return os.environ.get("GOROOT") or subprocess.check_output(["go", "env", "GOROOT"], text=True).strip()

def parse_debruijn(src: str):
    tables = {}
    for m in re.finditer(r'var (deBruijn\d+tab) = \[(\d+)\]byte\{([^}]*)\}', src):
        name, n, body = m.group(1), int(m.group(2)), m.group(3)
        bs = [int(t) for t in re.findall(r'\d+', body)]
        if len(bs) != n:
            raise SystemExit(f"{name}: expected {n} entries, got {len(bs)}")
        tables[name] = bs
    if set(tables) != {"deBruijn32tab", "deBruijn64tab"}:
        raise SystemExit(f"unexpected de Bruijn table set {sorted(tables)}")
    return tables

def parse_tables(src: str):
    tables = {}
    for m in re.finditer(r'const (\w+) = ""((?:\s*\+\s*"(?:\\x[0-9a-fA-F]{2})+")+)', src):
        name, body = m.group(1), m.group(2)
        bs = [int(h, 16) for h in re.findall(r'\\x([0-9a-fA-F]{2})', body)]
        if len(bs) != 256:
            raise SystemExit(f"{name}: expected 256 entries, got {len(bs)}")
        tables[name] = bs
    expected = {"ntz8tab", "pop8tab", "rev8tab", "len8tab"}
    if set(tables) != expected:
        raise SystemExit(f"unexpected table set {sorted(tables)}")
    return tables

def render(tables, sha, sha_bits, version):
    out = []
    out.append("-- Code generated by scripts/gen_bits_tables.py. DO NOT EDIT.")
    out.append(f"-- Source: $GOROOT/src/math/bits/bits_tables.go ({version}) sha256 {sha}")
    out.append(f"--         $GOROOT/src/math/bits/bits.go ({version}) sha256 {sha_bits}")
    out.append("set_option maxRecDepth 8192\nnamespace Go.Bits\n")
    out.append("/-- `tab[x]`: Go indexing into one of the lookup tables (0 outside the table; Go panics). -/")
    out.append("def tab {w : Nat} (t : Array (BitVec 8)) (x : BitVec w) : BitVec 8 := t.getD x.toNat 0\n")
    for name, bs in tables.items():
        n = len(bs)
        ibits = n.bit_length() - 1
        out.append(f"/-- Go `{name}` ({n} entries), transcribed byte-for-byte. -/")
        out.append(f"def {name} : Array (BitVec 8) := #[")
        rows = []
        for i in range(0, n, 16):
            rows.append("  " + ", ".join(f"0x{b:02x}" for b in bs[i:i+16]))
        out.append(",\n".join(rows))
        out.append("]\n")
        out.append(f"theorem {name}_size : {name}.size = {n} := by rfl\n")
        out.append(f"/-- The same table as a bit-blastable function of a {ibits}-bit index. -/")
        out.append(f"def {name}Fn (i : BitVec {ibits}) : BitVec 8 :=")
        chain = " else\n".join(f"  if i = {k} then 0x{b:02x}" for k, b in enumerate(bs[:-1]))
        out.append(chain + f" else 0x{bs[-1]:02x}\n")
        out.append(f"/-- Table lookup agrees with the function on every in-range index (kernel-checked). -/")
        out.append(f"theorem {name}_eq_fn : ∀ i : BitVec {ibits}, tab {name} i = {name}Fn i := by decide\n")
    out.append("end Go.Bits")
    return "\n".join(out) + "\n"

def main():
    check = "--check" in sys.argv
    path = os.path.join(goroot(), "src", "math", "bits", "bits_tables.go")
    data = open(path, "rb").read()
    version = open(os.path.join(goroot(), "VERSION")).readline().strip()
    bits_path = os.path.join(goroot(), "src", "math", "bits", "bits.go")
    bits = open(bits_path, "rb").read()
    tables = parse_tables(data.decode())
    tables.update(parse_debruijn(bits.decode()))
    text = render(tables, hashlib.sha256(data).hexdigest(), hashlib.sha256(bits).hexdigest(), version)
    dest = os.path.join(os.path.dirname(__file__), "..", "GoInLean", "Stdlib", "BitsTables.lean")
    if check:
        cur = open(dest).read()
        if cur != text:
            raise SystemExit("BitsTables.lean is out of date; rerun scripts/gen_bits_tables.py")
        print("BitsTables.lean up to date")
    else:
        open(dest, "w").write(text)
        print(f"wrote {dest}")

if __name__ == "__main__":
    main()
