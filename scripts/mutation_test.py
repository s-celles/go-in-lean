#!/usr/bin/env python3
"""Mutation test and counterexample-to-Go pipeline.

For each entry of mutants/mutants.json:
  1. run `lake env lean mutants/<file>.lean`; require a bv_decide
     counterexample ("The prover found a counterexample") for the mutant's
     theorem. A timeout, an unsupported-expression ("potentially spurious")
     result, a successful proof, or any other error FAILS the test;
  2. parse the assignment (`x = 123#64`) into concrete inputs;
  3. generate go/reproducers/mutant_<name>_test.go, which (a) asserts that
     the Go mutant in go/reference disagrees with the oracle on exactly this
     input and (b) asserts that the real math/bits function agrees with it;
  4. run `go test ./reproducers/...`.

The script is deterministic and offline. Exit status 0 only if every mutant
is refuted and reproduced.
"""
import json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CE_RE = re.compile(r"The prover found a counterexample, consider the following assignment:\n((?:\s*\w+ = \d+#\d+\n?)+)")
ASSIGN_RE = re.compile(r"(\w+) = (\d+)#(\d+)")

def run(cmd, cwd=ROOT):
    return subprocess.run(cmd, cwd=cwd, text=True, capture_output=True)

def lean_counterexample(path):
    r = run(["lake", "env", "lean", path])
    out = r.stdout + r.stderr
    if "potentially spurious" in out:
        return None, "spurious counterexample (unsupported expression abstracted); not a refutation:\n" + out
    if "timed out" in out:
        return None, "SAT timeout; not a refutation:\n" + out
    m = CE_RE.search(out)
    if not m:
        if r.returncode == 0:
            return None, "mutant theorem was PROVED: the specification does not detect this defect"
        return None, "unexpected error:\n" + out
    assign = {k: (int(v), int(w)) for k, v, w in ASSIGN_RE.findall(m.group(1))}
    return assign, out

GO_TEMPLATES = {
    # Compiler-rule mutant: we cannot run a mutated compiler, so the reproducer runs the REAL
    # compiled shift on the counterexample's inputs and requires Go semantics (the real lowering
    # must not exhibit the mutant's defect), and checks that the mutant's formula, evaluated in Go,
    # does exhibit it.
    "arm64_lsh64x32": '''
//go:noinline
func lsh64x32Real(x uint64, s uint64) uint64 {{ return x << uint32(s) }}

func Test{Name}(t *testing.T) {{
	var rx, ry uint64 = {rx}, {ry}
	want := uint64(0)
	if uint32(ry) < 64 {{
		want = rx << (uint32(ry) & 63)
	}}
	mutant := uint64(0)
	if ry < 64 {{ // the mutant compares the raw register
		mutant = rx << (ry & 63)
	}}
	if mutant == want {{
		t.Fatalf("counterexample does not distinguish the mutant: rx=%#x ry=%#x", rx, ry)
	}}
	if got := lsh64x32Real(rx, ry); got != want {{
		t.Fatalf("REAL compiled Lsh64x32 differs from Go semantics: rx=%#x ry=%#x got %#x want %#x -- investigate!", rx, ry, got, want)
	}}
}}
''',
    # Go mutant and real function share the signature; `oracle` is computed with math/big.
    "add64": '''
func Test{Name}(t *testing.T) {{
	x, y, carry := uint64({x}), uint64({y}), uint64({carry})
	// oracle: 128-bit sum
	want := new(big.Int).SetUint64(x)
	want.Add(want, new(big.Int).SetUint64(y))
	want.Add(want, new(big.Int).SetUint64(carry))
	check := func(name string, sum, co uint64) bool {{
		got := new(big.Int).Lsh(new(big.Int).SetUint64(co), 64)
		got.Or(got, new(big.Int).SetUint64(sum))
		return got.Cmp(want) == 0
	}}
	ms, mc := reference.{Name}(x, y, carry)
	if check("mutant", ms, mc) {{
		t.Fatalf("Lean counterexample did NOT reproduce against the Go mutant: %s(%#x,%#x,%d) = (%#x,%#x)", "{Name}", x, y, carry, ms, mc)
	}}
	rs, rc := {Real}(x, y, carry)
	if !check("real", rs, rc) {{
		t.Fatalf("REAL math/bits disagrees with the oracle on the counterexample: {Real}(%#x,%#x,%d) = (%#x,%#x) -- investigate!", x, y, carry, rs, rc)
	}}
}}
''',
    "u64_to_int": '''
func Test{Name}(t *testing.T) {{
	x := uint64({x})
	want := {Real}(x) // the real function is the oracle here; its own spec is tested in go/tests
	got := reference.{Name}(x)
	if got == want {{
		t.Fatalf("Lean counterexample did NOT reproduce against the Go mutant: {Name}(%#x) = %d = real", x, got)
	}}
	t.Logf("{Name}(%#x) = %d, {Real}(%#x) = %d (expected disagreement)", x, got, x, want)
}}
''',
    "u64_int_to_u64": '''
func Test{Name}(t *testing.T) {{
	var ku uint64 = {k}
	x, k := uint64({x}), int(int64(ku))
	want := {Real}(x, k)
	got := reference.{Name}(x, k)
	if got == want {{
		t.Fatalf("Lean counterexample did NOT reproduce against the Go mutant: {Name}(%#x, %d) = %#x = real", x, k, got)
	}}
	t.Logf("{Name}(%#x, %d) = %#x, {Real} = %#x (expected disagreement)", x, k, got, want)
}}
''',
}

HEADER = '''// Code generated by scripts/mutation_test.py from Lean counterexamples. DO NOT EDIT.
// Source mutant: mutants/{lean}  (theorem {theorem})
// Counterexample assignment: {assign}
package reproducers

import (
	"math/big"
	"math/bits"
	"testing"

	"github.com/s-celles/go-in-lean/go/reference"
)

var _ = big.NewInt
var _ = bits.Len
var _ = reference.Add64WrongCarry
'''

def main():
    mutants = json.load(open(os.path.join(ROOT, "mutants", "mutants.json")))
    repro_dir = os.path.join(ROOT, "go", "reproducers")
    os.makedirs(repro_dir, exist_ok=True)
    failures = []
    for m in mutants:
        name = m["go_mutant"]
        path = os.path.join("mutants", m["lean"])
        print(f"[{name}] compiling {path} ...", flush=True)
        assign, info = lean_counterexample(path)
        if assign is None:
            failures.append(f"{name}: {info}")
            print(f"  FAIL: {info.splitlines()[0]}")
            continue
        print(f"  refuted in model; counterexample {assign}")
        vals = {k: v for k, (v, _w) in assign.items()}
        tmpl = GO_TEMPLATES[m["signature"]]
        fmt = dict(Name=name, Real=m["go_real"])
        fmt.update({k: str(v) for k, v in vals.items()})
        try:
            body = tmpl.format(**fmt)
        except KeyError as e:
            failures.append(f"{name}: counterexample lacks variable {e}")
            continue
        src = HEADER.format(lean=m["lean"], theorem=m["theorem"], assign=assign) + body
        out = os.path.join(repro_dir, f"mutant_{name}_test.go")
        open(out, "w").write(src)
        print(f"  wrote {os.path.relpath(out, ROOT)}")
    r = run(["go", "test", "-count=1", "./reproducers/..."], cwd=os.path.join(ROOT, "go"))
    print(r.stdout.strip())
    if r.returncode != 0:
        failures.append("go test ./reproducers failed:\n" + r.stdout + r.stderr)
    if failures:
        print("\nMUTATION TEST FAILED:")
        for f in failures:
            print("  " + f.replace("\n", "\n    "))
        sys.exit(1)
    print(f"\nmutation test passed: {len(mutants)} mutants refuted in Lean and reproduced in Go")

if __name__ == "__main__":
    main()
