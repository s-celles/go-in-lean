#!/usr/bin/env python3
"""Translate the AMD64 shift-lowering rules of AMD64.rules into Lean theorems.
Same method as scripts/arm64_shift_rules.py (see its docstring): registers have
arbitrary bits above the Go type's width; machine ops in GoInLean/Compiler/AMD64.lean.
"""
import hashlib, os, re, subprocess, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from arm64_shift_rules import expand, tokenize, parse  # reuse the rule parser

GOROOT = os.environ.get("GOROOT") or subprocess.check_output(["go", "env", "GOROOT"], text=True).strip()
RULES = os.path.join(GOROOT, "src/cmd/compile/internal/ssa/_gen/AMD64.rules")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "GoInLean", "Compiler", "AMD64Shifts.lean")

BIN = {"SHLQ": "shlq", "SHRQ": "shrq", "SARQ": "sarq", "SHLL": "shll", "SHRL": "shrl", "SARL": "sarl",
       "SHRW": "shrw", "SARW": "sarw", "SHRB": "shrb", "SARB": "sarb",
       "ANDQ": "andq", "ANDL": "andl", "ORQ": "orq", "ORL": "orl"}
UN = {"NOTQ": "notq", "NOTL": "notl"}
CMPW = {"CMPQconst": 64, "CMPLconst": 32, "CMPWconst": 16, "CMPBconst": 8}

def lean(e):
    if isinstance(e, str):
        return {"x": "rx", "y": "ry"}[e]
    op, aux, args = e
    if op in BIN:
        return f"(X86.{BIN[op]} {lean(args[0])} {lean(args[1])})"
    if op in UN:
        return f"(X86.{UN[op]} {lean(args[0])})"
    if op in ("SBBQcarrymask", "SBBLcarrymask"):
        c = args[0]; cop, k, cargs = c
        assert cop in CMPW, c
        f = "sbbqCarrymask" if op.startswith("SBBQ") else "sbblCarrymask"
        return f"(X86.{f} (X86.cmpCarry {CMPW[cop]} {lean(cargs[0])} {k}))"
    raise ValueError("unsupported op " + op)

def main():
    src = open(RULES).read()
    sha = hashlib.sha256(src.encode()).hexdigest()
    thms, names = [], set()
    for lineno, line in enumerate(src.splitlines(), 1):
        s = line.strip()
        if not re.match(r"\((Lsh|Rsh)", s) or "shiftIsBounded" not in s:
            continue
        for r in expand(s):
            m = re.fullmatch(r"\((Lsh|Rsh)(\d+)(U?)x(\d+)\s+(?:<t>\s+)?x y\)\s*&&\s*(!?)shiftIsBounded\(v\)\s*=>\s*(.*)", r)
            if not m:
                raise SystemExit(f"unparsed rule at {lineno}: {r}")
            kind, W, U, A, neg, rhs = m.groups()
            W, A = int(W), int(A)
            body = lean(parse(tokenize(rhs))[0])
            go = {"Lsh": "x <<< y", "RshU": "x >>> y", "Rsh": "x.sshiftRight' y"}[kind + U]
            bounded = neg == ""
            name = f"{kind}{W}{U}x{A}_{'bounded' if bounded else 'unbounded'}"
            if name in names:
                raise SystemExit(f"duplicate rule instance {name} at line {lineno}: refusing to skip it silently")
            names.add(name)
            hyp = f"\n    (hb : ry.setWidth {A} < ({W} : BitVec {A}))" if bounded else ""
            thms.append(f"""/-- AMD64.rules:{lineno}  `{r}` -/
theorem {name} (rx ry : BitVec 64){hyp} :
    let x : BitVec {W} := rx.setWidth {W}
    let y : BitVec {A} := ry.setWidth {A}
    ({body}).setWidth {W} = {go} := by
  intro x y
  simp only [x, y, X86.shlq, X86.shrq, X86.sarq, X86.shll, X86.shrl, X86.sarl, X86.shrw, X86.sarw,
    X86.shrb, X86.sarb, X86.andq, X86.andl, X86.orq, X86.orl, X86.notq, X86.notl, X86.low, X86.put,
    X86.cmpCarry, X86.sbbqCarrymask, X86.sbblCarrymask]
  bv_decide
""")
            if W == 32:
                # AMD64latelower.rules relies on 32-bit results having zero upper halves
                # (`(MOVLQZX x) && zeroUpper32Bits(x,3) => x`).
                thms.append(f"""/-- Upper 32 bits of the lowered `{kind}{W}{U}x{A}` ({'bounded' if bounded else 'unbounded'}) are zero
(fact used by `AMD64latelower.rules`: `(MOVLQZX x) && zeroUpper32Bits(x,3) => x`). -/
theorem {name}_zeroUpper (rx ry : BitVec 64){hyp} :
    ({body}) >>> 32 = 0 := by
  simp only [X86.shlq, X86.shrq, X86.sarq, X86.shll, X86.shrl, X86.sarl, X86.shrw, X86.sarw,
    X86.shrb, X86.sarb, X86.andq, X86.andl, X86.orq, X86.orl, X86.notq, X86.notl, X86.low, X86.put,
    X86.cmpCarry, X86.sbbqCarrymask, X86.sbblCarrymask]
  bv_decide
""")
    text = f"""-- Code generated by scripts/amd64_shift_rules.py from AMD64.rules. DO NOT EDIT.
-- Source: $GOROOT/src/cmd/compile/internal/ssa/_gen/AMD64.rules sha256 {sha}
-- {len(thms)} shift-lowering rule instances.
import Std.Tactic.BVDecide
import GoInLean.Compiler.AMD64

namespace Go.Compiler.AMD64Shifts
open Go.Compiler

""" + "\n".join(thms) + "\nend Go.Compiler.AMD64Shifts\n"
    if "--check" in sys.argv:
        if open(OUT).read() != text:
            raise SystemExit("AMD64Shifts.lean is out of date; rerun scripts/amd64_shift_rules.py")
        print("AMD64Shifts.lean up to date"); return
    open(OUT, "w").write(text)
    print(f"wrote {os.path.relpath(OUT)}: {len(thms)} theorems")

if __name__ == "__main__":
    main()
