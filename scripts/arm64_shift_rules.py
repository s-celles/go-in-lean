#!/usr/bin/env python3
"""Translate the ARM64 shift-lowering rules of ARM64.rules into Lean theorems.

Scope: rules whose left-hand side is a generic Go shift
`(Lsh|Rsh|RshU){W}x{A} <t> x y` with `shiftIsBounded(v)` or its negation.
Alternations `(a|b|c)` are expanded in parallel (the k-th alternative of every
group in the rule), as rulegen does.

Machine model (the point of the exercise):
* a value of Go type uintN/intN (N < 64) lives in the low N bits of a 64-bit
  register; the upper bits are ARBITRARY ("we ignore high parts of
  registers", ARM64.rules). Each theorem quantifies over the whole register.
* SLL/SRL/SRA (register forms) shift by `amount & 63` (ARM64 LSLV/LSRV/ASRV).
* ZeroExtNto64 / SignExtNto64 extend the low N bits (MOVBU/MOVHU/MOVWU/...).
* CMPconst [k] e with cc LessThanU is the unsigned 64-bit test e < k.
* CSEL [cc] a b f = if cond(f) then a else b. Const64 [k] / MOVDconst [k].
Go semantics (spec): x << y, x >> y with y unsigned of width A and no upper
limit; `shiftIsBounded(v)` (set by the prove pass) means y < W.

Each theorem states: low W bits of the lowered value = Go result.
"""
import hashlib, os, re, subprocess, sys

GOROOT = os.environ.get("GOROOT") or subprocess.check_output(["go", "env", "GOROOT"], text=True).strip()
RULES = os.path.join(GOROOT, "src/cmd/compile/internal/ssa/_gen/ARM64.rules")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "GoInLean", "Compiler", "ARM64Shifts.lean")

def expand(rule):
    groups = re.findall(r"\(([^()\s]*\|[^()\s]*)\)", rule)
    if not groups:
        return [rule]
    alts = [g.split("|") for g in groups]
    n = len(alts[0])
    if any(len(a) != n for a in alts):
        raise ValueError("alternation length mismatch: " + rule)
    out = []
    for k in range(n):
        r = rule
        for g, a in zip(groups, alts):
            r = r.replace("(" + g + ")", a[k], 1)
        out.append(r)
    return out

def tokenize(s):
    return re.findall(r"\(|\)|\[[^\]]*\]|<[^>]*>|[^\s()]+", s)

def parse(tokens, i=0):
    t = tokens[i]
    if t == "(":
        op = tokens[i + 1]; i += 2
        aux, args = None, []
        while tokens[i] != ")":
            if tokens[i].startswith("["):
                aux = tokens[i][1:-1]; i += 1
            elif tokens[i].startswith("<"):
                i += 1
            else:
                a, i = parse(tokens, i); args.append(a)
        return (op, aux, args), i + 1
    return t, i + 1

def lean(e):
    if isinstance(e, str):
        return {"x": "rx", "y": "ry"}[e]
    op, aux, args = e
    if op in ("SLL", "SRL", "SRA"):
        return f"(Arm.{op.lower()} {lean(args[0])} {lean(args[1])})"
    m = re.fullmatch(r"(ZeroExt|SignExt)(\d+)to64", op)
    if m:
        return f"(Arm.{'zext' if m.group(1)=='ZeroExt' else 'sext'} {m.group(2)} {lean(args[0])})"
    if op in ("Const64", "MOVDconst"):
        return f"({aux} : BitVec 64)"
    if op == "CSEL":
        a, b, f = args
        fop, fk, fargs = f
        assert fop == "CMPconst" and aux == "OpARM64LessThanU", e
        return f"(if {lean(fargs[0])} < ({fk} : BitVec 64) then {lean(a)} else {lean(b)})"
    raise ValueError("unsupported op " + op)

def main():
    src = open(RULES).read()
    sha = hashlib.sha256(src.encode()).hexdigest()
    thms, names = [], set()
    for lineno, line in enumerate(src.splitlines(), 1):
        s = line.strip()
        if not re.match(r"\((Lsh|Rsh)", s) or "shiftIsBounded" not in s:
            continue
        for r in expand(s):
            m = re.fullmatch(r"\((Lsh|Rsh)(\d+)(U?)x(\d+)\s+(?:<t>\s+)?x y\)\s*&&\s*(!?)shiftIsBounded\(v\)\s*=>\s*(.*)", r)
            if not m:
                raise SystemExit(f"unparsed rule at {lineno}: {r}")
            kind, W, U, A, neg, rhs = m.groups()
            W, A = int(W), int(A)
            tree, _ = parse(tokenize(rhs))
            body = lean(tree)
            go = {"Lsh": "x <<< y", "RshU": "x >>> y", "Rsh": "x.sshiftRight' y"}[kind + U]
            bounded = neg == ""
            name = f"{kind}{W}{U}x{A}_{'bounded' if bounded else 'unbounded'}"
            if name in names:
                continue
            names.add(name)
            hyp = f"\n    (hb : ry.setWidth {A} < ({W} : BitVec {A}))" if bounded else ""
            thms.append(f"""/-- ARM64.rules:{lineno}  `{r}` -/
theorem {name} (rx ry : BitVec 64){hyp} :
    let x : BitVec {W} := rx.setWidth {W}
    let y : BitVec {A} := ry.setWidth {A}
    ({body}).setWidth {W} = {go} := by
  intro x y
  simp only [x, y, Arm.sll, Arm.srl, Arm.sra, Arm.zext, Arm.sext]
  bv_decide
""")
    text = f"""-- Code generated by scripts/arm64_shift_rules.py from ARM64.rules. DO NOT EDIT.
-- Source: $GOROOT/src/cmd/compile/internal/ssa/_gen/ARM64.rules sha256 {sha}
-- {len(thms)} shift-lowering rule instances.
import Std.Tactic.BVDecide
import GoInLean.Compiler.ARM64

namespace Go.Compiler.ARM64Shifts
open Go.Compiler

""" + "\n".join(thms) + "\nend Go.Compiler.ARM64Shifts\n"
    if "--check" in sys.argv:
        if open(OUT).read() != text:
            raise SystemExit("ARM64Shifts.lean is out of date; rerun scripts/arm64_shift_rules.py")
        print("ARM64Shifts.lean up to date"); return
    open(OUT, "w").write(text)
    print(f"wrote {os.path.relpath(OUT)}: {len(thms)} theorems")

if __name__ == "__main__":
    main()
