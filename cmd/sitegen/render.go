func badge(kind, value string) string {
	return "{{< badge " + quote(kind) + " " + quote(value) + " >}}"
}
func ref(label, path string) string {
	return "[" + strings.ReplaceAll(label, "]", `\]`) + "]({{< relref " + quote(path) + " >}})"
}

func (g *generator) page(path, title string, weight int, params map[string]any, body string) error {
	if _, ok := g.pages[path]; ok {
		return fmt.Errorf("duplicate generated page %s", path)
	}
	meta := map[string]any{"title": title, "weight": weight, "type": "docs", "params": params}
	if params == nil {
		delete(meta, "params")
	}
	if strings.HasPrefix(path, "properties/") && !strings.HasSuffix(path, "_index.md") {
		meta["aliases"] = []string{"/property/" + strings.TrimSuffix(filepath.Base(path), ".md") + "/"}
	}
	b, err := yaml.Marshal(meta)
	if err != nil {
		return err
	}
	g.pages[path] = []byte("---\n" + string(b) + "---\n\n<!-- Generated by cmd/sitegen. Edit the source data, not this page. -->\n\n" + body + "\n")
	return nil
}

func (g *generator) render() error {
	counts, trust, groups := map[string]int{}, map[string]int{}, map[string][]Property{}
	for _, p := range g.properties {
		counts[p.Status]++
		trust[p.Trust]++
		groups[p.Package] = append(groups[p.Package], p)
	}
	for _, pkg := range sortedKeys(groups) {
		s := slug(pkg)
		if other, ok := g.routes[s]; ok {
			return fmt.Errorf("package slug collision: %s / %s", pkg, other)
		}
		g.routes[s] = pkg
		for _, p := range groups[pkg] {
			if err := g.propertyPage(p, s); err != nil {
				return err
			}
		}
		body := "Properties registered for **" + pkg + "**. Status describes the model and recorded evidence, not a proof about a compiled Go binary.\n\n" + propertyTable(groups[pkg])
		if err := g.page("properties/"+s+"/_index.md", pkg, 10, nil, body); err != nil {
			return err
		}
	}
	registry := "{{< registry-controls >}}\n\nEvery row comes from " + link("targets/properties.yaml", repoLink("targets/properties.yaml")) + ". Select an area or a property to inspect its contract, theorem, oracle and executable checks.\n\n" + trustExplanation + "\n\n| Package / area | Registered | Proved in model | Reproduced in Go |\n|---|---:|---:|---:|\n"
	for _, pkg := range sortedKeys(groups) {
		proved, reproduced := 0, 0
		for _, p := range groups[pkg] {
			if p.Status == "proved_in_model" {
				proved++
			}
			if p.Status == "go_discrepancy_reproduced" {
				reproduced++
			}
		}
		registry += fmt.Sprintf("| %s | %d | %d | %d |\n", ref(cell(pkg), "/properties/"+slug(pkg)), len(groups[pkg]), proved, reproduced)
	}
	registry += "\n## All properties\n\n" + propertyTable(g.properties)
	if err := g.page("properties/_index.md", "Property registry", 20, nil, registry); err != nil {
		return err
	}
	for _, f := range g.findings {
		if err := g.findingPage(f); err != nil {
			return err
		}
	}
	findex := "{{< registry-controls >}}\n\nA registry of research findings, including negative controls and unreachable model counterexamples. A row is **not automatically a Go bug**. Classification and evidence are shown separately from upstream review state.\n\nPriorities are project triage labels, not upstream severity assessments: P0 critical impact; P1 wrong results on ordinary inputs; P2 edge cases or build failures; P3 controls, latent rules or negligible impact. No current entry claims demonstrated memory unsafety.\n\n"
	for _, priority := range []string{"P0", "P1", "P2", "P3"} {
		var fs []Finding
		for _, f := range g.findings {
			if f.Priority == priority {
				fs = append(fs, f)
			}
		}
		if len(fs) == 0 {
			continue
		}
		findex += "## " + priority + "\n\n| Finding | Area / architecture | Classification | Upstream |\n|---|---|---|---|\n"
		for _, f := range fs {
			findex += "| " + ref(f.ID, "/findings/"+slug(f.ID)) + " — " + cell(f.Title) + " | " + cell(f.Package) + " · " + cell(strings.Join(f.Architectures, ", ")) + " | " + badge("status", f.Status) + " | " + g.findingState(f) + " |\n"
		}
		findex += "\n"
	}
	if err := g.page("findings/_index.md", "Findings", 10, nil, findex); err != nil {
		return err
	}
	guide, err := g.read("docs/project.md")
	if err != nil {
		return err
	}
	pitch, err := projectPitch(string(guide))
	if err != nil {
		return err
	}
	home := "<div class=\"project-kicker\">Lean 4 · Go · executable evidence</div>\n\n" + pitch + "\n\n"
	home += "The " + ref("complete project guide", "/docs/project") + " covers the project results, research map, symbolic and concolic approaches, setup, repository layout and contribution policy.\n\n"
	home += fmt.Sprintf("{{< registry-summary registered=%q proved=%q reproduced=%q findings=%q >}}\n\n", fmt.Sprint(len(g.properties)), fmt.Sprint(counts["proved_in_model"]), fmt.Sprint(counts["go_discrepancy_reproduced"]), fmt.Sprint(len(g.findings)))
	home += ref("Browse findings →", "/findings") + " · " + ref("Explore the registry →", "/properties") + " · " + ref("Read the methodology →", "/about") + "\n\n## Verification status\n\nCounts are recomputed from the YAML on every build. Registry entries, audited theorems and research findings are different units; one entry can cite several theorems, and several entries can share one root cause.\n\n| Registry status | Entries |\n|---|---:|\n"
	for _, s := range statuses {
		home += fmt.Sprintf("| %s | %d |\n", badge("status", s), counts[s])
	}
	home += "\n## Trust and scope\n\n" + trustExplanation + fmt.Sprintf("\n\n| Recorded trust tier | Registry entries |\n|---|---:|\n| %s | %d |\n| %s | %d |\n\nThe counts include unresolved entries; a recorded trust tier alone does not establish a property.\n", badge("trust", "kernel"), trust["kernel"], badge("trust", "bv_decide"), trust["bv_decide"])
	home += "\n## Coverage by area\n\n| Area | Entries |\n|---|---:|\n"
	for _, pkg := range sortedKeys(groups) {
		home += fmt.Sprintf("| %s | %d |\n", ref(cell(pkg), "/properties/"+slug(pkg)), len(groups[pkg]))
	}
	home += "\nThe " + ref("SIMD and floating-point research", "/docs/fuzzing-vision") + " includes executable models and campaigns outside this manifest; it is not added to the property counts until registered.\n\n## Recent findings\n\n"
	newest := append([]Finding(nil), g.findings...)
	sort.Slice(newest, func(i, j int) bool {
		a, b := newest[i], newest[j]
		ad, bd := a.History[len(a.History)-1].Date, b.History[len(b.History)-1].Date
		if ad != bd {
			return ad > bd
		}
		return a.ID < b.ID
	})
	for i, f := range newest {
		if i == 5 {
			break
		}
		home += "- " + ref(f.Title, "/findings/"+slug(f.ID)) + " — " + badge("status", f.Status) + "\n"
	}
	if err := g.page("_index.md", "go-in-lean", 0, map[string]any{"description": "Finding correctness bugs in Go with bit-precise Lean models and executable evidence."}, home); err != nil {
		return err
	}
	about := pitch + "\n\n## From a contract to a finding\n\n1. Record the documented contract, preconditions and Go source revision.\n2. Model the implementation with fixed-width arithmetic and explicit outcomes.\n3. State a quantified Lean property and record its trust tier.\n4. Replay a model counterexample through real Go on the affected toolchain and architecture.\n5. Check model fidelity, reachability, existing issues and impact. A person reviews any upstream report.\n\nA failed proof is not evidence of a compiler defect. A counterexample may reveal a wrong model, a missing precondition, an ambiguity or an unreachable internal state. Even a reproduced discrepancy needs interpretation.\n\n## What the proofs establish\n\n" + trustExplanation + "\n\nProofs establish claims about the Lean model. Differential vectors, independent Go oracles, canaries and cross-architecture campaigns test how well that model follows Go. They do not turn a model theorem into a proof of the Go binary.\n\n## Two evidence registries\n\nThe property manifest records verification targets and their status transitions. Finding YAML records group research evidence, reproducers and upstream links, including discoveries made by fuzzing outside the manifest. Upstream state is read from the checked-in status document; a merged master fix does not prove a release branch is fixed.\n\n## Project and inspiration\n\nInspired by " + link("julia-in-lean", "https://github.com/MilesCranmer/julia-in-lean") + ", with its separation of proved properties, model refutations and runtime evidence. The goéland (seagull) identity and artwork come from the repository's " + link("brand assets", repository+"/tree/main/assets/brand") + ".\n\n" + ref("Prior art and limitations", "/docs/prior-art") + " · " + link("Source and contributors", repository) + "\n"
	if err := g.page("about/_index.md", "Methodology", 50, nil, about); err != nil {
		return err
	}
	docs := "Project research and contributor documentation, imported from the repository at build time.\n\n"
	imports := []struct{ Path, Title, Route string }{{"docs/project.md", "Project guide", "docs/project.md"}, {"docs/prior-art.md", "Prior art", "docs/prior-art.md"}, {"docs/fuzzing-vision.md", "Fuzzing vision", "docs/fuzzing-vision.md"}, {"docs/cedar-notes.md", "Research notes", "docs/cedar-notes.md"}, {"upstream-bugs.md", "Upstream bugs", "docs/upstream-bugs.md"}, {"CHANGELOG.md", "Changelog", "docs/changelog.md"}, {"docs/site.md", "Building this site", "docs/site.md"}, {"docs/upstream-status.md", "Upstream status", "upstream/_index.md"}}
	for i, item := range imports {
		b, err := g.read(item.Path)
		if err != nil {
			return err
		}
		body := removeTitle(string(b))
		body = rewriteLinks(body, item.Path)
		body = "Source: " + link(item.Path, repoLink(item.Path)) + ".\n\n" + body
		if strings.HasPrefix(item.Route, "upstream/") {
			body = "A checked-in snapshot of upstream issue and change states. Counts and tables are regenerated on build; this page does not query Gerrit or GitHub in your browser. A closed issue and a merged CL are separate events.\n\n" + body
		}
		if err := g.page(item.Route, item.Title, 30+i, nil, body); err != nil {
			return err
		}
		if strings.HasPrefix(item.Route, "docs/") {
			docs += "- " + ref(item.Title, "/"+strings.TrimSuffix(item.Route, ".md")) + "\n"
		}
	}
	return g.page("docs/_index.md", "Documentation", 40, nil, docs)
}

const trustExplanation = "**kernel** means the recorded theorem is checked by Lean's kernel without a per-theorem native-evaluation axiom. **bv_decide** additionally trusts the tactic's native-evaluation axiom for its generated certificate. These are distinct trust tiers, not interchangeable proof counts. See the manifest comments and the axiom audit for the precise boundary."

func propertyTable(ps []Property) string {
	s := "| Property | Function | Status | Recorded trust |\n|---|---|---|---|\n"
	for _, p := range ps {
		s += "| " + ref(p.ID, "/properties/"+slug(p.Package)+"/"+slug(p.ID)) + " | " + cell(p.Function) + " | " + badge("status", p.Status) + " | " + badge("trust", p.Trust) + " |\n"
	}
	return s
}

func (g *generator) propertyPage(p Property, area string) error {
	b := badge("status", p.Status) + " " + badge("trust", p.Trust) + "\n\n" + p.Doc + "\n\n| Field | Contract |\n|---|---|\n| Package / area | " + cell(p.Package) + " |\n| Function | " + cell(p.Function) + " |\n| Source citation | " + cell(goSourceLinks(p.GoSource)) + " |\n| Preconditions | " + cell(p.Preconditions) + " |\n| Postcondition | " + cell(p.Postcondition) + " |\n| Ambiguity risk | " + cell(p.AmbiguityRisk) + " |\n| Complexity | " + cell(p.Complexity) + " |\n\nSource paths above link to the modelled go1.25.5 tag when explicitly recorded as `src/...`; citations mentioning master, historical rules or other releases retain that scope. The original citation is preserved in the " + link("manifest", repoLink("targets/properties.yaml")) + ".\n\n## Lean statement\n\nThe manifest records the statement in prose/mathematical notation; the linked theorem is the authoritative Lean declaration.\n" + code("lean", p.LeanStatement) + "## Theorems and trust\n\n" + trustExplanation + "\n\n"
	if len(p.LeanTheorem) == 0 {
		b += "No general theorem is recorded for this entry.\n\n"
	} else {
		for _, name := range p.LeanTheorem {
			b += "- " + link("`"+name+"`", sourceLink(g.theorems[name])) + "\n"
		}
		b += "\n"
	}
	b += "## Independent oracle\n\n" + p.Oracle + "\n\n## Go checks\n\n"
	if len(p.GoTests) == 0 {
		b += "No standalone Go test is listed; consult the oracle and evidence below.\n\n"
	} else {
		for _, name := range p.GoTests {
			b += "- " + link("`"+name+"`", sourceLink(g.tests[name])) + "\n"
		}
		b += "\n"
	}
	if p.Evidence != "" {
		b += "## Evidence\n\n" + p.Evidence + "\n\n"
	}
	if p.Blocker != "" {
		b += "## Unresolved work\n\n" + p.Blocker + "\n\n"
	}
	for _, f := range g.findings {
		if f.ID == p.ID || strings.Contains(p.Evidence, "findings/"+f.ID) {
			b += "Related finding: " + ref(f.Title, "/findings/"+slug(f.ID)) + ".\n\n"
		}
	}
	b += timeline(p.History)
	return g.page("properties/"+area+"/"+slug(p.ID)+".md", p.ID+" · "+p.Function, 10, map[string]any{"status": p.Status, "trust": p.Trust, "package": p.Package}, b)
}

func (g *generator) findingState(f Finding) string {
	if len(f.Upstream) == 0 {
		return "No upstream report"
	}
	var parts []string
	for _, u := range f.Upstream {
		rows := g.upstreamFor(u)
		states := []string{}
		for _, r := range rows {
			state := strings.TrimSuffix(strings.Fields(r.State)[0], ",")
			if !contains(states, state) {
				states = append(states, state)
			}
		}
		parts = append(parts, link("#"+filepath.Base(u), u)+" · "+cell(strings.Join(states, " / ")))
	}
	return strings.Join(parts, "; ")
}

func contains(ss []string, s string) bool {
	for _, x := range ss {
		if x == s {
			return true
		}
	}
	return false
}

func (g *generator) findingPage(f Finding) error {
	b := badge("status", f.Status) + " **" + f.Priority + "** · " + f.Severity + "\n\n" + f.Summary + "\n\n| Field | Evidence scope |\n|---|---|\n| Package / area | " + cell(f.Package) + " |\n| Architectures | " + cell(strings.Join(f.Architectures, ", ")) + " |\n| Affected toolchains | " + cell(f.AffectedVersions) + " |\n| Source citation | " + cell(goSourceLinks(f.GoSource)) + " |\n| Research record | " + link(f.Report, repoLink(f.Report)) + " |\n\nThe affected-version statement records reproduction history. Consult upstream state for merged fixes and backports; it does not mean that every later revision remains affected.\n\n"
	for _, p := range f.SourceRecords {
		b += "Source analysis: " + link(p, repoLink(p)) + ".\n\n"
	}
	b += "## Counterexample and Lean evidence\n\n"
	if f.LeanFile != "" {
		raw, err := g.read(f.LeanFile)
		if err != nil {
			return err
		}
		b += "The standalone model evidence is recorded in " + link(f.LeanFile, repoLink(f.LeanFile)) + ". Some findings establish unsoundness of an internal rule rather than reachability from a Go program; use the classification above.\n" + code("lean", string(raw))
	} else {
		linked := false
		for _, p := range g.properties {
			if p.ID != f.ID {
				continue
			}
			if len(p.LeanTheorem) > 0 {
				linked = true
				b += "The registered model statement and its Lean declarations are linked below. The statement is recorded in mathematical notation; consult each declaration for its exact Lean type.\n" + code("lean", p.LeanStatement)
				for _, name := range p.LeanTheorem {
					b += "- " + link("`"+name+"`", sourceLink(g.theorems[name])) + "\n"
				}
				b += "\n"
			}
		}
		if !linked {
			b += "No standalone Lean proof file is registered for this finding. The executable counterexample and analysis are recorded in the " + link("research record", repoLink(f.Report)) + "; this page does not claim a proof that is absent from the evidence.\n\n"
		}
	}
	b += "## Go reproducer\n\n"
	if f.Reproducer != "" {
		raw, err := g.read(f.Reproducer)
		if err != nil {
			return err
		}
		b += "Exact source: " + link(f.Reproducer, repoLink(f.Reproducer)) + ". Build tags, target architecture and toolchain requirements in this file are part of the reproduction instructions.\n" + code("go", string(raw))
	} else {
		b += "The " + link("research record", repoLink(f.Report)) + " contains the counterexample snippets and campaign instructions; no standalone reproducer file is registered.\n\n"
	}
	b += "## Upstream issue and fixes\n\n"
	if len(f.Upstream) == 0 {
		b += "No upstream report is recorded. This may be a control, an unreachable rule or a discrepancy for which reporting is not proposed.\n\n"
	} else {
		b += "States come from " + ref("the checked-in upstream status snapshot", "/upstream") + ". An issue's state does not imply that all release branches contain its fix.\n\n| Issue / PR | Issue state | Change list | Change state | Scope |\n|---|---|---|---|---|\n"
		for _, u := range f.Upstream {
			for _, r := range g.upstreamFor(u) {
				b += "| " + r.Item + " | " + cell(r.State) + " | " + r.CL + " | " + cell(r.CLState) + " | " + cell(r.Note) + " |\n"
			}
		}
		b += "\n"
	}
	for _, p := range g.properties {
		if p.ID == f.ID {
			b += "Registry entry: " + ref(p.ID, "/properties/"+slug(p.Package)+"/"+slug(p.ID)) + ".\n\n"
		}
	}
	b += timeline(f.History) + "\nMetadata: " + link("findings/"+f.ID+".yaml", repoLink("findings/"+f.ID+".yaml")) + ".\n"
	return g.page("findings/"+slug(f.ID)+".md", f.Title, 10, map[string]any{"status": f.Status, "package": f.Package, "priority": f.Priority, "description": f.Summary}, b)
}

func timeline(history []History) string {
	s := "## History\n\n| Date | Classification | Note |\n|---|---|---|\n"
	for _, h := range history {
		s += "| " + h.Date + " | " + badge("status", h.Status) + " | " + cell(h.Note) + " |\n"
	}
	return s + "\n"
}
func removeTitle(s string) string {
	lines := strings.Split(s, "\n")
	if len(lines) > 0 && strings.HasPrefix(lines[0], "# ") {
		return strings.TrimSpace(strings.Join(lines[1:], "\n"))
	}
	return strings.TrimSpace(s)
}
func projectPitch(s string) (string, error) {
	start := strings.Index(s, "**Finding correctness")
	if start < 0 {
		return "", fmt.Errorf("project guide pitch marker not found")
	}
	end := strings.Index(s[start:], "> **About the name.")
	if end < 0 {
		return "", fmt.Errorf("project guide pitch end marker not found")
	}
	return strings.TrimSpace(s[start : start+end]), nil
}
